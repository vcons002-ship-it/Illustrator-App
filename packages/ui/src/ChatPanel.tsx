export type MessageBlock =
  | { type: "text"; text: string }
  | { type: "code"; lang: string; code: string; filename?: string };

/** Split a message into prose and fenced ```code``` blocks (saveable as files). The
 * fence's info string may carry a filename after the language (```html index.html`,
 * ```js src/app.js`, or just ```index.html`) so a multi-file answer keeps real names. */
export function parseMessageBlocks(text: string): MessageBlock[] {
  const blocks: MessageBlock[] = [];
  const re = /```([^\n`]*)\r?\n([\s\S]*?)```/g;
  let last = 0;
  for (const m of text.matchAll(re)) {
    const i = m.index;
    if (i > last) blocks.push({ type: "text", text: text.slice(last, i) });
    const { lang, filename } = parseFenceInfo(m[1] ?? "");
    blocks.push(
      ...splitRunTogetherFiles({ type: "code", lang, code: m[2]!.replace(/\n$/, ""), ...(filename ? { filename } : {}) }),
    );
    last = i + m[0].length;
  }
  if (last < text.length) blocks.push({ type: "text", text: text.slice(last) });
  return blocks.length ? blocks : [{ type: "text", text }];
}

/** A body line long enough that it's prose, not a fence header someone forgot to fence. */
const MAX_HEADER_LINE = 120;

/**
 * Split ONE code block that is really SEVERAL files run together, because the model wrote the second
 * and third files' fence headers as ordinary lines INSIDE the first block instead of opening new
 * fences.
 *
 * Asked for three haikus as separate documents, a local model produced one ```text haiku_6.txt block
 * whose body was haiku 6, then the bare line `text haiku_7.txt`, then haiku 7, then `text haiku_8.txt`,
 * then haiku 8. The reader gets one file card for three files, and no button in the app can undo that
 * — every downstream feature (Save, Save all as project, Open in app) reads the parsed blocks. Nothing
 * about the model's INTENT is ambiguous here: it named three files, in the exact grammar the fence line
 * uses. So the app reads what was written rather than what was fenced.
 *
 * Deliberately narrow, because a false split silently corrupts a real file. A cut requires all of:
 * the block itself is named (the model was naming files), the line is exactly two tokens, the first is
 * the block's OWN language verbatim, and the second is a filename with an extension. `text haiku_7.txt`
 * inside a ```text haiku_6.txt block is that; a bare `README.md` line — which is ordinary content in a
 * document listing files — is NOT, and is left alone. PURE.
 */
export function splitRunTogetherFiles(
  block: Extract<MessageBlock, { type: "code" }>,
): Extract<MessageBlock, { type: "code" }>[] {
  if (!block.filename || !block.lang) return [block];
  const lines = block.code.split("\n");
  const cuts: { at: number; filename: string }[] = [];
  for (let i = 0; i < lines.length; i++) {
    const raw = lines[i]!.trim();
    if (!raw || raw.length > MAX_HEADER_LINE) continue;
    const tokens = raw.split(/\s+/);
    if (tokens.length !== 2 || tokens[0]!.toLowerCase() !== block.lang) continue;
    const name = tokens[1]!;
    if (!/\.[A-Za-z0-9]+$/.test(name)) continue;
    cuts.push({ at: i, filename: name });
  }
  if (cuts.length === 0) return [block];
  const parts: Extract<MessageBlock, { type: "code" }>[] = [];
  const push = (filename: string, from: number, to: number): void => {
    const code = lines.slice(from, to).join("\n").replace(/^\n+|\n+$/g, "");
    if (code.trim()) parts.push({ type: "code", lang: block.lang, code, filename });
  };
  push(block.filename, 0, cuts[0]!.at);
  for (let k = 0; k < cuts.length; k++) {
    push(cuts[k]!.filename, cuts[k]!.at + 1, cuts[k + 1]?.at ?? lines.length);
  }
  // A run of headers with no bodies isn't several files — leave the block as the model wrote it.
  return parts.length > 1 ? parts : [block];
}

const looksLikeFilename = (s: string): boolean => /[^/\s]+\.[A-Za-z0-9]+$/.test(s) || s.includes("/");

/** Parse a fence info string into a language + optional filename, tolerating
 * `lang filename`, `lang title="filename"`, and a bare `filename`. */
export function parseFenceInfo(info: string): { lang: string; filename?: string } {
  const tokens = info.trim().split(/\s+/).filter(Boolean);
  if (tokens.length === 0) return { lang: "" };
  const cleaned = tokens.map((t) =>
    t.replace(/^(?:title|name|file|filename)=/i, "").replace(/^["']|["']$/g, ""),
  );
  // A bare `filename.ext` as the first token: derive the language from its extension.
  if (looksLikeFilename(cleaned[0]!) && !LANG_EXT[tokens[0]!.toLowerCase()]) {
    return { lang: (cleaned[0]!.split(".").pop() ?? "").toLowerCase(), filename: cleaned[0]! };
  }
  const lang = tokens[0]!.toLowerCase();
  const filename = cleaned.slice(1).find(looksLikeFilename);
  return filename ? { lang, filename } : { lang };
}

/** Resolve a code block's display filename + save name (basename) + mime, preferring
 * an explicit fence filename over the language's generic default. */
export function resolveCodeFile(lang: string, filename?: string): { filename: string; saveName: string; mime: string } {
  if (filename) {
    const ext = (filename.split(".").pop() ?? "").toLowerCase();
    const base = filename.split("/").pop() || filename;
    return { filename, saveName: base, mime: fileForLang(ext).mime };
  }
  const { ext, base, mime } = fileForLang(lang);
  return { filename: `${base}.${ext}`, saveName: `${base}.${ext}`, mime };
}

/** Collect a message's code blocks into project files (named for the zip). */
export function projectFilesFromBlocks(blocks: MessageBlock[]): ProjectFile[] {
  return blocks
    .filter((b): b is Extract<MessageBlock, { type: "code" }> => b.type === "code")
    .map((b) => ({ name: b.filename ?? resolveCodeFile(b.lang, b.filename).filename, content: b.code }));
}

/** What each parsed block should RENDER as: prose `text`, a saveable `file` card, or an inline read-only
 * `snippet`. Snippets are the fix for document fragmentation — a research doc full of illustrative code
 * examples used to shatter into one saveable "file" card per fence. */
export type BlockKind = "text" | "file" | "snippet";

/** A bare (un-named) sole code block at least this big reads as "the file the model just made" (e.g. a
 * whole HTML page); smaller un-named blocks are illustrative snippets and render inline. */
const SAVEABLE_SOLE_MIN_CHARS = 400;

/**
 * Decide, per block, whether a fenced code block is a SAVEABLE FILE or an inline SNIPPET — so a document
 * with embedded examples stops fragmenting into many file cards. A block is a file when it (a) carries a
 * filename hint (the model named it), or (b) is the SOLE code block and DOMINATES the reply (more code
 * than prose, and non-trivial) — i.e. the "here's the whole file" answer. Everything else is an inline
 * snippet. Genuine multi-file answers (several filename-tagged blocks) stay files. PURE. */
export function classifyBlocks(blocks: MessageBlock[]): BlockKind[] {
  const code = blocks.filter((b): b is Extract<MessageBlock, { type: "code" }> => b.type === "code");
  const codeChars = code.reduce((n, b) => n + b.code.length, 0);
  const proseChars = blocks.reduce((n, b) => n + (b.type === "text" ? b.text.trim().length : 0), 0);
  const soleDominant = code.length === 1 && codeChars >= proseChars && codeChars >= SAVEABLE_SOLE_MIN_CHARS;
  return blocks.map((b): BlockKind => {
    if (b.type === "text") return "text";
    if (b.filename) return "file";
    return soleDominant ? "file" : "snippet";
  });
}

