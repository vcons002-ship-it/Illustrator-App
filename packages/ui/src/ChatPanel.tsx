function CodeCard({
  lang,
  code,
  filename: rawFilename,
  onSaveFile,
  onRunCode,
  fileActions,
  desktop,
}: {
  lang: string;
  code: string;
  filename?: string;
  onSaveFile?: (filename: string, content: string, mime: string) => Promise<string | true>;
  onRunCode?: RunCodeFn;
  /** Universal file-card actions (open in app / library / on PC) for the file this block creates. */
  fileActions?: FileActions;
  desktop?: boolean;
}) {
  const [copied, setCopied] = useState(false);
  const [saved, setSaved] = useState<string | undefined>();
  const [previewOpen, setPreviewOpen] = useState(false);
  const [running, setRunning] = useState(false);
  const [output, setOutput] = useState<RunCodeResult | undefined>();
  // Object URLs handed to new tabs, revoked on unmount as well as by the grace timer —
  // a card unmounted before the timer fires must not leak its blob.
  const tabUrls = useRef<Set<string>>(new Set());
  useEffect(() => {
    const urls = tabUrls.current;
    return () => {
      for (const u of urls) URL.revokeObjectURL(u);
    };
  }, []);
  const { filename, saveName, mime } = resolveCodeFile(lang, rawFilename);
  const ext = (filename.split(".").pop() ?? "").toLowerCase();
  const previewable = ext === "html" || ext === "svg";
  const l = (lang || "").toLowerCase();
  const runnable = !!onRunCode && (["py", "js", "sh"].includes(ext) || ["python", "js", "javascript", "node", "sh", "bash", "shell"].includes(l));
  const save = async () => {
    if (!onSaveFile) return;
    try {
      const r = await onSaveFile(saveName, code, mime);
      setSaved(typeof r === "string" ? r : "saved");
    } catch (e) {
      // Surface a failed save where the "saved to …" note would go — not an unhandled rejection.
      setSaved(`save failed: ${e instanceof Error ? e.message : String(e)}`);
    }
  };
  const run = async () => {
    if (!onRunCode) return;
    setRunning(true);
    setOutput(undefined);
    try {
      setOutput(await onRunCode(lang, code, rawFilename));
    } catch (e) {
      setOutput({ error: e instanceof Error ? e.message : String(e) });
    } finally {
      setRunning(false);
    }
  };
  // Open the rendered page in a new tab (a real click → not blocked). The 30s grace
  // period gives the tab time to load before the blob URL is revoked.
  const openInTab = () => {
    const url = URL.createObjectURL(new Blob([code], { type: mime }));
    tabUrls.current.add(url);
    window.open(url, "_blank", "noreferrer");
    setTimeout(() => {
      tabUrls.current.delete(url);
      URL.revokeObjectURL(url);
    }, 30_000);
  };
  return (
    <div style={codeCardStyle}>
      <div style={codeHeaderStyle}>
        <span style={{ opacity: 0.7 }} title={filename}>{lang || "text"} · {filename}</span>
        <span style={{ display: "flex", gap: 6 }}>
          {onSaveFile && (
            <button style={codeBtnStyle} onClick={() => void save()}>
              💾 Save
            </button>
          )}
          {runnable && (
            <button style={codeBtnStyle} onClick={() => void run()} disabled={running} title="Run this code on the desktop and show its output here">
              {running ? "Running…" : "▶ Run"}
            </button>
          )}
          {previewable && (
            <button style={codeBtnStyle} onClick={() => setPreviewOpen((o) => !o)} title="Render it right here in the chat">
              {previewOpen ? "▾ Hide preview" : "▶ Preview"}
            </button>
          )}
          {previewable && (
            <button
              style={codeBtnStyle}
              onClick={openInTab}
              title="Open the rendered page in a new browser tab"
              aria-label="Open the rendered page in a new browser tab"
            >
              ↗ Tab
            </button>
          )}
          <button
            style={codeBtnStyle}
            onClick={() => {
              void navigator.clipboard?.writeText(code);
              setCopied(true);
              setTimeout(() => setCopied(false), 1200);
            }}
          >
            {copied ? "Copied" : "📋 Copy"}
          </button>
        </span>
      </div>
      {fileActions ? (
        // The created file's universal actions (Save above is the Download; these add the rest).
        <FileActionBar
          file={{ name: filename, mime, kind: runnable || /^(ts|tsx|js|jsx|py|rb|go|rs|java|c|cpp|sh|css|json)$/.test(ext) ? "code" : "text", content: code }}
          actions={{
            ...(fileActions.openInApp ? { openInApp: fileActions.openInApp } : {}),
            ...(fileActions.openInLibrary ? { openInLibrary: fileActions.openInLibrary } : {}),
            ...(fileActions.openOnPC ? { openOnPC: fileActions.openOnPC } : {}),
          }}
          {...(desktop ? { desktop } : {})}
        />
      ) : null}
      {previewOpen && previewable ? (
        // Sandboxed in-app render: scripts run (so a coded page/widget actually works) but it has no
        // same-origin access — it can't touch the app, cookies, or storage.
        <iframe
          title={`Preview of ${filename}`}
          srcDoc={code}
          sandbox="allow-scripts allow-forms allow-popups allow-modals"
          style={{ width: `100%`, height: 320, border: `1px solid ${t.fill.strong}`, borderRadius: 6, background: `#fff` }}
        />
      ) : (
        <pre style={codePreStyle}>
          <code>{code}</code>
        </pre>
      )}
      {output && (
        <pre style={{ ...codePreStyle, borderTop: `1px solid ${t.border.subtle}`, opacity: 0.95 }}>
          <code>
            {output.error
              ? `⚠ ${output.error}`
              : `[exit ${output.code ?? "?"}${output.cwd ? ` · in ${output.cwd}` : ""}]` +
                (output.stdout ? `\n${output.stdout.slice(0, 6000)}` : "") +
                (output.stderr ? `\n⚠ ${output.stderr.slice(0, 3000)}` : "") +
                (!output.stdout && !output.stderr ? "\n(no output)" : "")}
          </code>
        </pre>
      )}
      {saved && (
        <div style={{ fontSize: 11, opacity: 0.7, padding: "4px 8px" }}>
          {saved === "saved" ? "✓ Saved (check your downloads)" : `✓ Saved to ${saved}`}
        </div>
      )}
    </div>
  );
}

