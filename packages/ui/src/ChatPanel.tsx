/** Object URL for a bytes image (revoked on change); pass-through for hotlinks. */
function useMessageImageUrl(image: ChatMessageVM["image"]): string | undefined {
  const bytes = image && "bytes" in image ? image : undefined;
  const [url, setUrl] = useState<string | undefined>(undefined);
  useEffect(() => {
    if (!bytes) {
      setUrl(undefined);
      return;
    }
    const objectUrl = URL.createObjectURL(new Blob([bytes.bytes], { type: bytes.mimeType }));
    setUrl(objectUrl);
    return () => URL.revokeObjectURL(objectUrl);
  }, [bytes]);
  if (image && "sourceUrl" in image) return image.sourceUrl;
  return url;
}

