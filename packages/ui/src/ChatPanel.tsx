/** Collapsible context-usage readout — a one-line summary that expands to the
 * donut + legend. Shared by both chat panels. */
export const UsageDisclosure = memo(function UsageDisclosure({ usage }: { usage: ContextUsage }) {
  const pct =
    usage.maxTokens !== undefined
      ? ` · ${Math.min(100, Math.round((usage.approxTokens / usage.maxTokens) * 100))}% of window`
      : "";
  const used = usage.approxTokens >= 1000 ? `${(usage.approxTokens / 1000).toFixed(1)}k` : usage.approxTokens;
  return (
    <details style={usageDetailsStyle}>
      <summary style={usageSummaryStyle}>
        Context: ~{used} tokens{pct} — see breakdown
      </summary>
      <div style={{ padding: "6px 10px 10px" }}>
        <ContextUsageDonut usage={usage} />
      </div>
    </details>
  );
});

const usageDetailsStyle = { borderBottom: "1px solid rgba(255,255,255,0.08)" } as const;
const usageSummaryStyle = {
  cursor: "pointer",
  fontSize: 11,
  opacity: 0.7,
  padding: "6px 12px",
  listStyle: "revert",
} as const;

// Memoised: every keystroke in the draft (panel-local state) and every streamed
// token re-renders the panel — settled bubbles (which can hold images and link
// lists, and grow without bound over a session) must not re-render with it.
// Exported for the landing-page buddy panel, which renders the same bubbles.
// `onDelete(index)` must be a STABLE callback for the same reason — a per-bubble
// closure would defeat the memo.
export const MessageBubble = memo(function MessageBubble({
  message,
  index,
  onDelete,
  onOpenLocalFile,
}: {
  message: ChatMessageVM;
  index?: number;
  onDelete?: (index: number) => void;
  /** Open a local-file result (desktop `/find`). Stable callback (memo). */
  onOpenLocalFile?: (path: string) => void;
}) {
  const isUser = message.role === "user";
  const url = useMessageImageUrl(message.image);
  return (
    <div
      style={{
        ...bubbleStyle,
        alignSelf: isUser ? "flex-end" : "flex-start",
        background: isUser ? "rgba(122,162,255,0.18)" : "rgba(255,255,255,0.06)",
      }}
    >
      {onDelete !== undefined && index !== undefined && (
        <button
          style={deleteButtonStyle}
          title="Delete this message (it leaves the conversation the model sees too)"
          aria-label="Delete message"
          onClick={() => onDelete(index)}
        >
          ✕
        </button>
      )}
      {message.text ? <div style={{ whiteSpace: "pre-wrap" }}>{message.text}</div> : null}
      {url ? (
        <img src={url} alt="Chat image" decoding="async" style={{ maxWidth: "100%", borderRadius: 6, marginTop: message.text ? 6 : 0 }} />
      ) : null}
      {message.links?.length ? (
        <ol style={{ margin: "6px 0 0", paddingLeft: 18, fontSize: 11 }}>
          {message.links.map((l, i) => (
            <li key={i}>
              <a href={l.url} target="_blank" rel="noreferrer" style={{ color: "#9db8ff" }}>
                {l.title || l.url}
              </a>
            </li>
          ))}
        </ol>
      ) : null}
      {message.files?.length ? (
        <div style={{ display: "flex", flexDirection: "column", gap: 4, marginTop: 6 }}>
          {message.files.map((f, i) => (
            <button
              key={i}
              style={fileChipStyle}
              title={`Open ${f.path}`}
              onClick={() => onOpenLocalFile?.(f.path)}
            >
              📄 {f.name}
            </button>
          ))}
        </div>
      ) : null}
    </div>
  );
});

