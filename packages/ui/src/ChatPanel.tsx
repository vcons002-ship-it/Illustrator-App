/** Stable React keys for a chat message list. Keys on each message's `at` timestamp, disambiguating
 * two messages that share a millisecond with an ordinal, and falling back to the index only when `at`
 * is absent. Stable across a delete — the removed message's key simply disappears and every other
 * bubble keeps its key — so a bubble's child state (CodeCard run output, iframe preview, gallery zoom)
 * stays attached to its own message instead of shifting onto a neighbour (U1). */
export function chatMessageKeys(messages: ChatMessageVM[]): string[] {
  const seen = new Map<number, number>();
  return messages.map((m, i) => {
    if (m.at === undefined) return `i${i}`;
    const n = seen.get(m.at) ?? 0;
    seen.set(m.at, n + 1);
    return `t${m.at}-${n}`;
  });
}

