/**
 * The universal file card's action bar — shown under ANY file the assistant created or found:
 * Download, Open in app, Open in library, Open on PC. Only the actions provided AND applicable to
 * the file/platform render; the first stays inline and the rest collapse into a ▾ More dropdown so
 * the row stays compact. One component, reused for code blocks, found files, and surfaced artifacts.
 */
export function FileActionBar({
  file,
  actions,
  desktop,
  label,
}: {
  file: FileRef;
  actions: FileActions;
  desktop?: boolean;
  /** Show the file name as a leading chip (used by the attachments list; off inside a CodeCard). */
  label?: boolean;
}) {
  const [busy, setBusy] = useState<string | undefined>();
  /** What the last action did, shown under the bar. Saving a document used to report NOTHING —
   * not where it went, not that it had happened, and not why it hadn't: the click set the chip to
   * "…" and then put it back, which from the outside is a button that does nothing whether it
   * worked or threw. Every other Save in the app says "✓ Saved to …"; this one is where the
   * assistant's own documents come out, so it's the one that most needed to. */
  const [note, setNote] = useState<{ ok: boolean; text: string } | undefined>();
  const [readOpen, setReadOpen] = useState(false);
  // The "⋯ More" menu is a native <details> — collapse it after a pick, or it stays open covering the
  // chat until the reader clicks the summary again (U5).
  const moreRef = useRef<HTMLDetailsElement>(null);
  const closeMore = (): void => {
    if (moreRef.current) moreRef.current.open = false;
  };
  // Reading a text document INLINE, without leaving the chat. The card's own text when it carries it;
  // otherwise fetched on the first click, because the most common way a `.md` reaches the chat is as a
  // bare path (the assistant wrote it, or a search found it) — which used to mean a Markdown file the
  // chat could render perfectly well had no button to render it, only "open it somewhere else".
  const ownText = useMemo(() => inlineReadableText(file), [file]);
  const [loadedText, setLoadedText] = useState<string | undefined>();
  const [readErr, setReadErr] = useState<string | undefined>();
  const [reading, setReading] = useState(false);
  const inlineText = ownText ?? loadedText;
  const canReadInline = ownText !== undefined || (isTextDocument(file) && !!actions.readText);
  const toggleRead = async (): Promise<void> => {
    if (readOpen) return setReadOpen(false);
    setReadOpen(true);
    if (inlineText !== undefined || !actions.readText) return;
    setReading(true);
    setReadErr(undefined);
    try {
      const text = await actions.readText(file);
      // `undefined` is "couldn't get it"; `""` is "got it, it's empty". Collapsing the two reported a
      // file that read perfectly well as unreachable — and the other way round, a blank panel would
      // have read as "this file is empty" when the file was simply out of reach.
      if (text === undefined) setReadErr(`Couldn't read “${file.name}” from here.`);
      else if (text.trim() === "") setReadErr(`“${file.name}” is empty.`);
      else setLoadedText(text);
    } catch (e) {
      setReadErr(`Couldn't read “${file.name}”: ${e instanceof Error ? e.message : String(e)}`);
    } finally {
      setReading(false);
    }
  };
  const runFor: Record<FileActionKey, () => void | Promise<unknown>> = {
    dl: async () => {
      const saved = await actions.download!(file);
      // undefined = the reader cancelled the name prompt. Nothing happened, so say nothing.
      if (saved === undefined) return;
      setNote({ ok: true, text: saved === true ? "✓ Saved (check your downloads)" : `✓ Saved to ${saved}` });
    },
    app: () => actions.openInApp!(file),
    lib: () => actions.openInLibrary!(file),
    pc: () => actions.openOnPC!(file),
  };
  const items: FileActionItem[] = fileActionKeys(
    file.kind,
    { download: !!actions.download, openInApp: !!actions.openInApp, openInLibrary: !!actions.openInLibrary, openOnPC: !!actions.openOnPC },
    desktop,
  ).map((key) => ({ key, ...FILE_ACTION_LABEL[key], run: runFor[key] }));
  if (items.length === 0) return null;
  const fire = async (it: FileActionItem) => {
    setBusy(it.key);
    setNote(undefined);
    try {
      await it.run();
    } catch (e) {
      // NOT swallowed. This used to be an empty catch trusting "the app surfaces its own error note",
      // which for a failed save it doesn't — so the one visible sign of a broken Save was the chip
      // going back to normal.
      setNote({ ok: false, text: `⚠ ${it.label} failed: ${e instanceof Error ? e.message : String(e)}` });
    } finally {
      setBusy(undefined);
    }
  };
  const primary = items[0]!;
  const rest = items.slice(1);
  return (
    <div>
    <div style={{ display: "flex", alignItems: "center", gap: 6, marginTop: 6, flexWrap: "wrap" }}>
      {label ? <span style={{ opacity: 0.7, fontSize: 11, marginRight: 2 }}>📎 {file.name}</span> : null}
      <button style={fileChipStyle} title={primary.title} disabled={busy === primary.key} onClick={() => void fire(primary)}>
        {busy === primary.key ? "…" : primary.label}
      </button>
      {canReadInline ? (
        <button
          style={readOpen ? { ...fileChipStyle, borderColor: t.accent.edge, color: t.accent.text } : fileChipStyle}
          title="Read this document right here in the chat (no need to open the reader)"
          disabled={reading}
          onClick={() => void toggleRead()}
        >
          {reading ? "…" : readOpen ? "▾ Hide" : "📖 Read here"}
        </button>
      ) : null}
      {rest.length >= 1 || actions.openAs ? (
        <details ref={moreRef} style={{ position: "relative" }}>
          <summary style={{ ...fileChipStyle, listStyle: "none", cursor: "pointer" }}>⋯ More</summary>
          <div style={fileMenuStyle}>
            {rest.map((it) => (
              <button
                key={it.key}
                style={fileMenuItemStyle}
                title={it.title}
                disabled={busy === it.key}
                onClick={() => {
                  closeMore();
                  void fire(it);
                }}
              >
                {it.label}
              </button>
            ))}
            {actions.openAs ? (
              <>
                <div style={{ opacity: 0.5, fontSize: 10, padding: "4px 8px 2px" }}>Open as…</div>
                {OPEN_AS_CHOICES.map((c) => (
                  <button
                    key={c.as}
                    style={fileMenuItemStyle}
                    onClick={() => {
                      closeMore();
                      actions.openAs!(file, c.as);
                    }}
                  >
                    {c.label}
                  </button>
                ))}
              </>
            ) : null}
          </div>
        </details>
      ) : null}
    </div>
    {note ? (
      <div style={{ fontSize: 11, marginTop: 4, opacity: note.ok ? 0.7 : 1, color: note.ok ? undefined : DANGER_RED }}>
        {note.text}
      </div>
    ) : null}
    {readOpen && readErr ? (
      <div style={{ fontSize: 11, marginTop: 4, color: DANGER_RED }}>⚠ {readErr}</div>
    ) : null}
    {readOpen && inlineText !== undefined ? (
      <div
        style={{
          maxHeight: 440,
          overflowY: "auto",
          marginTop: 8,
          padding: "12px 16px",
          border: `1px solid ${t.border.subtle}`,
          borderRadius: 8,
          background: t.fill.subtle,
        }}
      >
        <DocBlocksView markdown={inlineText} />
      </div>
    ) : null}
    </div>
  );
}

